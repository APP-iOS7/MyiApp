import Foundation

/// 계정 삭제 기능을 제공하는 타입을 표시하는 프로토콜입니다.
///
/// 채택한 타입은 사용자의 계정과 관련 데이터를 영구적으로 제거하기 위해
/// `deleteAccount()` 메서드를 구현해야 합니다. 이 프로토콜은 `Sendable`을
/// 상속하므로, 채택한 타입은 동시성 환경 전반에서 안전하게 사용될 수 있어야 합니다.
///
/// 고려 사항:
/// - 되돌릴 수 없는 작업인 만큼, 삭제 실행 전 사용자 인터페이스나 호출자에게
///   충분히 명확하게 안내해야 합니다.
/// - 삭제 과정이 비동기이거나 시간이 걸릴 수 있다면(예: 네트워크 I/O),
///   비동기 오버로드 제공 또는 진행 상태 보고 같은 메커니즘을 함께 고려하세요.
/// - 사용자 데이터 삭제 시 플랫폼 및 지역의 데이터 보존·개인정보 관련 규정을
///   준수해야 합니다.
public protocol AccountDeletable: Sendable {
    func deleteAccount() async throws
}
