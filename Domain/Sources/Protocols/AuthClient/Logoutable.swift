import Foundation

/// 표준화된 비동기 로그아웃 작업을 정의하는 프로토콜입니다. 오류를 던질 수 있습니다.
///
/// 채택 타입은 사용자 로그아웃에 필요한 정리 및 상태 전환을 수행하기 위해
/// 하나의 `logout()` 메서드를 구현합니다. 예를 들어 다음을 포함할 수 있습니다:
/// - 인증 토큰 및 자격 증명의 폐기/삭제
/// - 메모리, 캐시, 영구 저장소에 있는 민감한 데이터 정리
/// - 메모리 내 세션 상태 및 사용자별 구성 초기화
/// - 로그아웃 이벤트를 종속 시스템/서비스에 알림
///
/// 동시성:
/// - 로그아웃 작업은 `async`로, 네트워크 또는 디스크 I/O를 수행할 수 있습니다.
/// - 프로토콜은 `Sendable`을 상속하므로, 구현 타입이 송신 가능성(sendability)을
///   보장하는 한 동시성 도메인 간에 안전하게 사용할 수 있습니다.
///
/// 오류 처리:
/// - `logout()`은 네트워크 오류, 저장 실패, 정책 위반 등의 실패를 전달하기 위해 `throws`를 사용합니다.
///   호출자는 오류를 처리하고 재시도, UI 표시, 축소된 상태로의 전환 등을 결정해야 합니다.
///
/// 사용 방법:
/// - 비동기 컨텍스트에서 `await`를 사용해 `logout()`을 호출합니다.
/// - 인증된 세션에 의존하는 UI나 상태를 성공적인 로그아웃 이후에 반드시 갱신하세요.
/// - 멱등성을 고려하세요: `logout()`을 여러 번 호출해도 안전하며 시스템을 불일치 상태로
///   만들지 않아야 합니다.
///
/// 예시:
/// ```swift
/// struct SessionManager: Logoutable {
///     func logout() async throws {
///         // 토큰 폐기, 캐시 정리, 상태 초기화 등
///     }
/// }
/// ```
///
/// - Note: 구현 시 블로킹 작업을 피하고 가능한 한 비동기 API를 사용하세요.
/// - Important: 로그아웃에 사용자 상호작용(예: 재인증 프롬프트)이 필요한 경우,
///   호출 지점에서 안전하게 UI를 표시할 수 있도록 `logout()` 주변 API를 설계하세요.
public protocol Logoutable: Sendable {
    func logout() async throws(AuthError)
}
